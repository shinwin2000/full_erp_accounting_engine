"""
Tests for domain/coa/aggregate_root.py

Covers COAStatus, ChartOfAccounts (entity-style methods, aggregate-root
account lifecycle methods, event methods, query methods), COAAggregate
(command wrapper), and COARepository/InMemoryCOARepository.

======================================================================
KNOWN BUGS IN THE SOURCE (verified by direct execution):

BUG-COA-AGGREGATE-001 — `approve(account_id, approved_by)` and
`reject(account_id, rejected_by, reason)` take NO `user_role` parameter.
Internally they call `self.can_approve(account_id, "finance_manager")` /
`self.can_reject(account_id, "finance_manager")` with a HARDCODED role
string, completely independent of who `approved_by`/`rejected_by`
actually is. There is no way to make the authorization check fail based
on the caller's real role -- any caller can approve/attempt-to-reject any
DRAFT account. Confirmed: `coa.approve(account_id, approved_by="random_user")`
succeeds with no role validation whatsoever.

BUG-COA-AGGREGATE-002 — `ChartOfAccounts._events` (like `_audit_trail`) is
declared `ClassVar[list[DomainEvent]]`, so it is a single list SHARED by
every `ChartOfAccounts` instance in the process, not per-aggregate.
Confirmed: two unrelated `ChartOfAccounts` objects (different `coa_id`,
different `legal_entity_id`) share the literal same `_events` list object,
so `get_events()` on one aggregate returns events generated by a
completely different aggregate elsewhere in the program.

BUG-COA-AGGREGATE-003 — `reject()` calls `acc.deactivate(rejected_by,
reason)`, but `can_reject()` only allows accounts in `AccountStatus.DRAFT`.
`AccountEntity.deactivate()` only succeeds from `ACTIVE` (it raises
"Cannot deactivate account in status draft" otherwise). Since DRAFT is the
only status `can_reject()` permits, **`reject()` can never succeed** --
it always raises ValueError regardless of input.

BUG-COA-AGGREGATE-004 — `reopen()` calls `acc.activate(reopened_by)`, but
`can_reopen()` only allows accounts in `AccountStatus.SUSPENDED`.
`AccountEntity.activate()` only succeeds from `DRAFT` (it raises
"Cannot activate account in status suspended" otherwise). Since SUSPENDED
is the only status `can_reopen()` permits, **`reopen()` can never
succeed** either.

BUG-COA-AGGREGATE-005 — `cancel()` calls `acc.delete(cancelled_by,
reason)`, but `can_cancel()` allows both `DRAFT` and `SUSPENDED`.
`AccountEntity.delete()` only succeeds from `DRAFT` or `ARCHIVED`. So
`cancel()` works from DRAFT, but **always fails from SUSPENDED** even
though `can_cancel()` says it should be allowed.

Net effect: of the account-level lifecycle transitions offered by
`ChartOfAccounts` beyond `add_child`/`post`, only `approve()` (with its
broken authorization) and `cancel()` from DRAFT and `close()` (ACTIVE ->
SUSPENDED, via `deactivate()`) reliably work end-to-end today.
======================================================================
"""

