class TestAddRemoveChild:
    def test_add_child_success(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        updated = coa.add_child(acc, "user_a")
        assert acc.id in updated.accounts
        assert updated.accounts[acc.id].status == AccountStatus.DRAFT
        assert updated.account_by_code["1000"] == acc.id

    def test_add_child_on_locked_coa_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        acc = make_account(legal_entity_id)
        with pytest.raises(ValueError, match="cannot add account"):
            coa.add_child(acc, "user_a")

    def test_add_child_duplicate_id_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        coa2 = coa.add_child(acc, "user_a")
        with pytest.raises(ValueError, match="already exists"):
            coa2.add_child(acc, "user_a")

    def test_add_child_duplicate_code_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc1 = make_account(legal_entity_id, code=AccountCodeVO("1000"))
        coa2 = coa.add_child(acc1, "user_a")
        acc2 = make_account(legal_entity_id, code=AccountCodeVO("1000"))
        with pytest.raises(ValueError, match="already exists"):
            coa2.add_child(acc2, "user_a")

    def test_add_child_missing_parent_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id, parent_id=uuid4())
        with pytest.raises(ValueError, match="Parent account"):
            coa.add_child(acc, "user_a")

    def test_add_child_with_valid_parent_computes_level(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        parent = make_account(legal_entity_id, code=AccountCodeVO("1000"))
        coa2 = coa.add_child(parent, "user_a")
        child = make_account(legal_entity_id, code=AccountCodeVO("1001"), parent_id=parent.id)
        coa3 = coa2.add_child(child, "user_a")
        assert coa3.accounts[child.id].level == 1

    def test_add_child_registers_event(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        updated = coa.add_child(acc, "user_a")
        events = updated.get_events()
        assert len(events) >= 1

    def test_remove_child_success(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        coa2 = coa.add_child(acc, "user_a")
        coa3 = coa2.remove_child(acc.id, "user_b")
        assert acc.id not in coa3.accounts
        assert "1000" not in coa3.account_by_code

    def test_remove_child_not_found_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        with pytest.raises(ValueError, match="not found"):
            coa.remove_child(uuid4(), "user_b")

    def test_remove_child_with_children_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        parent = make_account(legal_entity_id, code=AccountCodeVO("1000"))
        coa2 = coa.add_child(parent, "user_a")
        child = make_account(legal_entity_id, code=AccountCodeVO("1001"), parent_id=parent.id)
        coa3 = coa2.add_child(child, "user_a")
        with pytest.raises(ValueError, match="children"):
            coa3.remove_child(parent.id, "user_b")

    def test_remove_child_on_locked_coa_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        coa2 = coa.add_child(acc, "user_a")
        locked = coa2.lock("user_a", "reason")
        with pytest.raises(ValueError, match="cannot remove account"):
            locked.remove_child(acc.id, "user_b")


