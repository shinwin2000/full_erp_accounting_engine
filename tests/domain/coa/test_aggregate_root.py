class TestCOAAggregate:
    def test_init_without_coa(self):
        agg = COAAggregate()
        assert agg.coa is None
        assert agg.version == 1
        assert agg.id is None

    def test_init_with_coa(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        assert agg.coa is coa
        assert agg.version == coa.version
        assert agg.id == coa.coa_id

    def test_create_initializes_coa(self, legal_entity_id):
        agg = COAAggregate()
        agg.create(legal_entity_id, "New COA", "description", "user_a")
        assert agg.coa is not None
        assert agg.coa.status == COAStatus.ACTIVE
        assert agg.version == 1

    def test_load(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate()
        agg.load(coa)
        assert agg.coa is coa
        assert agg.id == coa.coa_id

    def test_add_account_without_loaded_coa_raises(self, legal_entity_id):
        agg = COAAggregate()
        acc = make_account(legal_entity_id)
        with pytest.raises(ValueError, match="COA not loaded"):
            agg.add_account(acc, "user_a")

    def test_add_account_updates_state_and_pulls_events(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        acc = make_account(legal_entity_id)
        agg.add_account(acc, "user_a")
        assert acc.id in agg.coa.accounts
        assert agg.version == agg.coa.version
        assert len(agg.get_events()) == 1

    def test_update_account_not_implemented(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        acc = make_account(legal_entity_id)
        with pytest.raises(NotImplementedError):
            agg.update_account(acc, "user_a")

    def test_deactivate_account(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        acc = make_account(legal_entity_id)
        agg.add_account(acc, "user_a")
        agg.deactivate_account(acc.id, "user_b")
        assert acc.id not in agg.coa.accounts

    def test_lock_unlock(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        agg.lock("user_a", "reason")
        assert agg.coa.status == COAStatus.LOCKED
        agg.unlock("user_b")
        assert agg.coa.status == COAStatus.ACTIVE

    def test_archive(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        agg = COAAggregate(coa)
        agg.archive("user_a", "old")
        assert agg.coa.status == COAStatus.ARCHIVED

    def test_apply_and_replay(self):
        from domain.coa.domain_events import COACreatedEvent

        agg = COAAggregate()
        event = COACreatedEvent(
            aggregate_id=uuid4(), aggregate_version=1, coa_name="X",
            legal_entity_id=uuid4(), created_by="user_a",
        )
        agg.replay([event])
        assert agg.get_events() == [event]

    def test_reconstruct_is_alias_for_replay(self):
        from domain.coa.domain_events import COACreatedEvent

        agg = COAAggregate()
        event = COACreatedEvent(
            aggregate_id=uuid4(), aggregate_version=1, coa_name="X",
            legal_entity_id=uuid4(), created_by="user_a",
        )
        agg.reconstruct([event])
        assert agg.get_events() == [event]

    def test_pop_events_is_alias_for_pull_events(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        acc = make_account(legal_entity_id)
        agg.add_account(acc, "user_a")
        popped = agg.pop_events()
        assert len(popped) == 1
        assert agg.get_events() == []

    def test_domain_events_property(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        acc = make_account(legal_entity_id)
        agg.add_account(acc, "user_a")
        assert len(agg.domain_events) == 1

    def test_snapshot_without_coa(self):
        agg = COAAggregate()
        snap = agg.snapshot()
        assert snap["coa_id"] is None

    def test_snapshot_with_coa(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        agg = COAAggregate(coa)
        snap = agg.snapshot()
        assert snap["coa_id"] == str(coa.coa_id)


