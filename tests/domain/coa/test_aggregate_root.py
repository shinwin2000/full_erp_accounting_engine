class TestInMemoryCOARepository:
    @pytest.fixture
    def repo(self):
        return InMemoryCOARepository()

    async def test_save_and_get_by_id(self, repo, legal_entity_id):
        coa = make_coa(legal_entity_id)
        await repo.save(coa)
        fetched = await repo.get_by_id(coa.coa_id)
        assert fetched is coa

    async def test_get_by_id_missing_returns_none(self, repo):
        assert await repo.get_by_id(uuid4()) is None

    async def test_get_by_legal_entity(self, repo, legal_entity_id):
        coa = make_coa(legal_entity_id)
        await repo.save(coa)
        fetched = await repo.get_by_legal_entity(legal_entity_id)
        assert fetched is coa

    async def test_get_by_legal_entity_missing_returns_none(self, repo):
        assert await repo.get_by_legal_entity(uuid4()) is None

    async def test_delete(self, repo, legal_entity_id):
        coa = make_coa(legal_entity_id)
        await repo.save(coa)
        await repo.delete(coa.coa_id)
        assert await repo.get_by_id(coa.coa_id) is None
        assert await repo.get_by_legal_entity(legal_entity_id) is None

    async def test_delete_nonexistent_does_not_raise(self, repo):
        await repo.delete(uuid4())

    async def test_list_all(self, repo, legal_entity_id):
        coa1 = make_coa(legal_entity_id)
        coa2 = make_coa(uuid4())
        await repo.save(coa1)
        await repo.save(coa2)
        all_coas = await repo.list_all()
        assert len(all_coas) == 2

    async def test_clear(self, repo, legal_entity_id):
        coa = make_coa(legal_entity_id)
        await repo.save(coa)
        await repo.clear()
        assert await repo.list_all() == []

    async def test_conforms_to_repository_protocol_methods(self, repo):
        # COARepository is a plain (non-runtime_checkable) Protocol, so
        # isinstance() checks against it raise TypeError. Verify structural
        # conformance directly instead.
        assert hasattr(repo, "get_by_id")
        assert hasattr(repo, "get_by_legal_entity")
        assert hasattr(repo, "save")
        assert hasattr(repo, "delete")


