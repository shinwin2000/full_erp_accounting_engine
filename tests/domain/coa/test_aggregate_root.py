class TestChartOfAccountsBasics:
    def test_create_records_audit(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        result = coa.create("user_a")
        assert result is coa
        assert coa.audit_trail()[-1]["action"] == "CREATE"

    def test_update_active_coa_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        updated = coa.update("user_b", name="Renamed COA")
        assert updated.name == "Renamed COA"
        assert updated.version == coa.version + 1

    def test_update_locked_coa_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        with pytest.raises(ValueError, match="cannot update"):
            coa.update("user_b", name="x")

    def test_delete_with_no_accounts_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        deleted = coa.delete("user_c", reason="unused")
        assert deleted.status == COAStatus.ARCHIVED

    def test_delete_with_accounts_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        coa2 = coa.add_child(acc, "user_a")
        with pytest.raises(ValueError, match="Cannot delete COA with existing accounts"):
            coa2.delete("user_c")

    def test_restore_from_archived_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.ARCHIVED)
        restored = coa.restore("user_d")
        assert restored.status == COAStatus.ACTIVE

    def test_restore_from_non_archived_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.ACTIVE)
        with pytest.raises(ValueError, match="Cannot restore"):
            coa.restore("user_d")

    def test_activate_from_locked_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        activated = coa.activate("user_e")
        assert activated.status == COAStatus.ACTIVE

    def test_deactivate_from_active_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.ACTIVE)
        deactivated = coa.deactivate("user_f", reason="pause")
        assert deactivated.status == COAStatus.LOCKED

    def test_lock_from_active_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.ACTIVE)
        locked = coa.lock("user_g", "year-end")
        assert locked.status == COAStatus.LOCKED

    def test_lock_from_non_active_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        with pytest.raises(ValueError, match="Cannot lock"):
            coa.lock("user_g", "reason")

    def test_unlock_from_locked_succeeds(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.LOCKED)
        unlocked = coa.unlock("user_h")
        assert unlocked.status == COAStatus.ACTIVE

    def test_unlock_from_non_locked_raises(self, legal_entity_id):
        coa = make_coa(legal_entity_id, status=COAStatus.ACTIVE)
        with pytest.raises(ValueError, match="Cannot unlock"):
            coa.unlock("user_h")

    def test_touch_bumps_version(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        touched = coa.touch("user_i")
        assert touched.version == coa.version + 1

    def test_validate_valid_coa(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        result = coa.validate()
        assert result["is_valid"] is True

    def test_validate_short_name_invalid(self, legal_entity_id):
        coa = make_coa(legal_entity_id, name="AB")
        result = coa.validate()
        assert result["is_valid"] is False
        assert any("at least 3 characters" in e for e in result["errors"])

    def test_to_dict_and_from_dict_round_trip(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        d = coa.to_dict()
        restored = ChartOfAccounts.from_dict(d)
        assert restored.coa_id == coa.coa_id
        assert restored.name == coa.name
        assert restored.status == coa.status

    def test_clone_creates_new_empty_active_coa(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        acc = make_account(legal_entity_id)
        coa_with_account = coa.add_child(acc, "user_a")
        cloned = coa_with_account.clone()
        assert cloned.coa_id != coa.coa_id
        assert cloned.status == COAStatus.ACTIVE
        assert cloned.accounts == {}
        assert "(COPY)" in cloned.name

    def test_clone_with_explicit_name(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        cloned = coa.clone(new_name="Custom Clone Name")
        assert cloned.name == "Custom Clone Name"

    def test_snapshot_contains_expected_fields(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        snap = coa.snapshot()
        assert snap["coa_id"] == str(coa.coa_id)
        assert snap["status"] == "active"
        assert "timestamp" in snap

    def test_get_version(self, legal_entity_id):
        coa = make_coa(legal_entity_id)
        assert coa.get_version() == 1


