#!/usr/bin/env python3
"""
Module: aggregate_root.py
Layer: Domain / Subledger AR
Responsibility: Root aggregate for Accounts Receivable subledger.

This aggregate manages invoices, payments, credit notes, and customer cards
for a specific legal entity. It enforces business invariants such as:
- Total outstanding balance cannot be negative.
- A payment cannot exceed the outstanding balance of the customer.
- Credit notes cannot exceed the invoice balance.
- Customer card balance must match the sum of its invoices minus payments/credits.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import UTC, datetime
from decimal import Decimal
from typing import Any
from uuid import UUID, uuid4

from domain.subledger_ar.aging_bucket_vo import AgingBucket
from domain.subledger_ar.customer_card import CustomerCard
from domain.subledger_ar.domain_events import (
    CreditNoteIssuedEvent,
    DomainEvent,
    InvoiceIssuedEvent,
    InvoicePaidEvent,
    PaymentReceivedEvent,
)
from domain.subledger_ar.invoice_entity import ARInvoice, InvoiceEntity
from domain.subledger_ar.payment_entity import PaymentEntity

logger = logging.getLogger(__name__)


# ============================================================================
# CUSTOM EXCEPTIONS
# ============================================================================

class ARSubledgerError(Exception):
    """Base exception for AR subledger errors."""
    pass


class InvoiceNotFoundError(ARSubledgerError):
    """Raised when an invoice is not found."""
    pass


class PaymentNotFoundError(ARSubledgerError):
    """Raised when a payment is not found."""
    pass


class CustomerNotFoundError(ARSubledgerError):
    """Raised when a customer card is not found."""
    pass


class InsufficientBalanceError(ARSubledgerError):
    """Raised when a payment or credit note exceeds the outstanding balance."""
    pass


class InvalidOperationError(ARSubledgerError):
    """Raised when an operation is not allowed in the current state."""
    pass


# ============================================================================
# AR SUBLEDGER AGGREGATE ROOT
# ============================================================================

@dataclass
class ARSubledger:
    """
    Aggregate root for Accounts Receivable subledger.

    This aggregate manages all AR transactions for a single legal entity.
    It ensures that all invoices, payments, and credit notes are consistent
    and that the total outstanding balance is correctly maintained.

    Attributes:
        ar_id: Unique identifier for this AR subledger.
        legal_entity_id: Legal entity that owns this subledger.
        invoices: Dictionary of invoices keyed by invoice ID.
        payments: Dictionary of payments keyed by payment ID.
        customer_cards: Dictionary of customer cards keyed by customer ID.
        credit_notes: Dictionary of credit notes keyed by credit note ID.
        debit_notes: Dictionary of debit notes keyed by debit note ID.
        created_at: Timestamp when this subledger was created.
        updated_at: Timestamp of the last update.
        version: Optimistic locking version number.
        _events: List of domain events generated by this aggregate.
        _audit_trail: Internal audit trail for debugging and compliance.
        _snapshots: Historical snapshots for recovery.
    """

    ar_id: UUID
    legal_entity_id: UUID
    invoices: dict[UUID, InvoiceEntity] = field(default_factory=dict)
    payments: dict[UUID, PaymentEntity] = field(default_factory=dict)
    customer_cards: dict[UUID, CustomerCard] = field(default_factory=dict)
    credit_notes: dict[UUID, Any] = field(default_factory=dict)
    debit_notes: dict[UUID, Any] = field(default_factory=dict)
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    updated_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    version: int = 1
    _events: list[DomainEvent] = field(default_factory=list, repr=False)
    _audit_trail: list[dict[str, Any]] = field(default_factory=list, repr=False)
    _snapshots: list[dict[str, Any]] = field(default_factory=list, repr=False)

    def __post_init__(self) -> None:
        """Validate invariants after initialization."""
        self._validate_invariants()

    def _validate_invariants(self) -> None:
        """
        Validate all business invariants.

        Raises:
            ARSubledgerError: If any invariant is violated.
        """
        # Check that total outstanding is non-negative
        total_outstanding = self.get_total_outstanding()
        if total_outstanding < 0:
            raise ARSubledgerError(
                f"Total outstanding balance cannot be negative: {total_outstanding}"
            )

        # Check that each customer card balance matches its invoices minus payments/credits
        for customer_id, card in self.customer_cards.items():
            card_balance = card.outstanding_balance
            calculated_balance = self._calculate_customer_balance(customer_id)
            if abs(card_balance - calculated_balance) > Decimal("0.01"):
                logger.warning(
                    "Customer %s balance mismatch: card=%s, calculated=%s",
                    customer_id,
                    card_balance,
                    calculated_balance,
                )

    def _calculate_customer_balance(self, customer_id: UUID) -> Decimal:
        """Calculate the customer's outstanding balance from invoices and payments."""
        total_invoiced = Decimal(0)
        total_paid = Decimal(0)
        total_credited = Decimal(0)

        for invoice in self.invoices.values():
            if invoice.customer_id == customer_id:
                total_invoiced += invoice.amount
                total_paid += invoice.paid_amount
                # Credit notes applied to this invoice
                for cn in self.credit_notes.values():
                    if cn.invoice_id == invoice.invoice_id:
                        total_credited += cn.amount

        return total_invoiced - total_paid - total_credited

    def _record_audit(
        self,
        action: str,
        performed_by: str,
        details: dict[str, Any] | None = None,
    ) -> None:
        """Record an audit trail entry."""
        entry = {
            "action": action,
            "performed_by": performed_by,
            "timestamp": datetime.now(UTC).isoformat(),
            "version": self.version,
            "ar_id": str(self.ar_id),
            "details": details or {},
        }
        self._audit_trail.append(entry)

    def _register_event(self, event: DomainEvent) -> None:
        """Register a domain event."""
        self._events.append(event)

    def _take_snapshot(self) -> None:
        """Take a snapshot of the current state for recovery."""
        snapshot = {
            "version": self.version,
            "ar_id": str(self.ar_id),
            "legal_entity_id": str(self.legal_entity_id),
            "invoice_count": len(self.invoices),
            "payment_count": len(self.payments),
            "customer_count": len(self.customer_cards),
            "total_outstanding": str(self.get_total_outstanding()),
            "timestamp": datetime.now(UTC).isoformat(),
        }
        self._snapshots.append(snapshot)
        # Keep only last 10 snapshots
        if len(self._snapshots) > 10:
            self._snapshots.pop(0)

    def _copy_with(self, **kwargs: Any) -> ARSubledger:
        """Create a new instance with updated fields."""
        return ARSubledger(
            ar_id=kwargs.get("ar_id", self.ar_id),
            legal_entity_id=kwargs.get("legal_entity_id", self.legal_entity_id),
            invoices=kwargs.get("invoices", self.invoices),
            payments=kwargs.get("payments", self.payments),
            customer_cards=kwargs.get("customer_cards", self.customer_cards),
            credit_notes=kwargs.get("credit_notes", self.credit_notes),
            debit_notes=kwargs.get("debit_notes", self.debit_notes),
            created_at=kwargs.get("created_at", self.created_at),
            updated_at=kwargs.get("updated_at", datetime.now(UTC)),
            version=kwargs.get("version", self.version + 1),
        )

    # ==================== BUSINESS METHODS ====================

    def add_invoice(self, invoice: InvoiceEntity, created_by: str) -> ARSubledger:
        """
        Add a new invoice to the subledger.

        Args:
            invoice: The invoice to add.
            created_by: ID of the user creating the invoice.

        Returns:
            A new ARSubledger instance with the invoice added.

        Raises:
            InvoiceAlreadyExistsError: If the invoice already exists.
        """
        if invoice.invoice_id in self.invoices:
            raise ARSubledgerError(f"Invoice {invoice.invoice_id} already exists")

        # Ensure customer card exists or create one
        customer_card = self.customer_cards.get(invoice.customer_id)
        if customer_card:
            new_card = customer_card.add_invoice(invoice)
        else:
            new_card = CustomerCard.create_from_invoice(invoice)

        new_invoices = self.invoices.copy()
        new_invoices[invoice.invoice_id] = invoice

        new_cards = self.customer_cards.copy()
        new_cards[invoice.customer_id] = new_card

        self._register_event(
            InvoiceIssuedEvent(
                aggregate_id=self.ar_id,
                aggregate_version=self.version + 1,
                invoice=invoice,
                issued_by=created_by,
            )
        )
        self._record_audit("ADD_INVOICE", created_by, {"invoice_id": str(invoice.invoice_id)})
        logger.info("Invoice %s added to AR subledger %s", invoice.invoice_id, self.ar_id)

        return self._copy_with(
            invoices=new_invoices,
            customer_cards=new_cards,
        )

    def add_payment(self, payment: PaymentEntity, received_by: str) -> ARSubledger:
        """
        Record a payment received from a customer.

        Args:
            payment: The payment to record.
            received_by: ID of the user recording the payment.

        Returns:
            A new ARSubledger instance with the payment applied.

        Raises:
            CustomerNotFoundError: If the customer does not exist.
            InsufficientBalanceError: If the payment exceeds the customer's outstanding balance.
        """
        if payment.customer_id not in self.customer_cards:
            raise CustomerNotFoundError(f"Customer {payment.customer_id} not found")

        # Validate payment amount against outstanding balance
        customer_card = self.customer_cards[payment.customer_id]
        if payment.amount > customer_card.outstanding_balance + Decimal("0.01"):
            raise InsufficientBalanceError(
                f"Payment amount {payment.amount} exceeds customer's outstanding balance "
                f"{customer_card.outstanding_balance}"
            )

        new_payments = self.payments.copy()
        new_payments[payment.payment_id] = payment

        # Update customer card
        new_card = customer_card.add_payment(payment)
        new_cards = self.customer_cards.copy()
        new_cards[payment.customer_id] = new_card

        # If payment is allocated to a specific invoice, update that invoice
        new_invoices = self.invoices.copy()
        if payment.allocated_to_invoice_id:
            invoice = self.invoices.get(payment.allocated_to_invoice_id)
            if invoice:
                new_invoice = invoice.record_payment(payment.amount, payment.payment_id)
                new_invoices[invoice.invoice_id] = new_invoice
                self._register_event(
                    InvoicePaidEvent(
                        aggregate_id=self.ar_id,
                        aggregate_version=self.version + 1,
                        invoice=new_invoice,
                        payment_id=payment.payment_id,
                        payment_amount=payment.amount,
                    )
                )

        self._register_event(
            PaymentReceivedEvent(
                aggregate_id=self.ar_id,
                aggregate_version=self.version + 1,
                payment=payment,
                received_by=received_by,
            )
        )
        self._record_audit("ADD_PAYMENT", received_by, {"payment_id": str(payment.payment_id)})
        logger.info("Payment %s added to AR subledger %s", payment.payment_id, self.ar_id)

        return self._copy_with(
            payments=new_payments,
            customer_cards=new_cards,
            invoices=new_invoices,
        )

    def add_credit_note(self, credit_note: Any, issued_by: str) -> ARSubledger:
        """
        Add a credit note to the subledger.

        Args:
            credit_note: The credit note to add.
            issued_by: ID of the user issuing the credit note.

        Returns:
            A new ARSubledger instance with the credit note applied.

        Raises:
            InvoiceNotFoundError: If the referenced invoice does not exist.
            InsufficientBalanceError: If the credit note exceeds the invoice balance.
        """
        invoice_id = getattr(credit_note, "invoice_id", None)
        if not invoice_id or invoice_id not in self.invoices:
            raise InvoiceNotFoundError(f"Invoice {invoice_id} not found")

        invoice = self.invoices[invoice_id]
        if credit_note.amount > invoice.amount - invoice.paid_amount:
            raise InsufficientBalanceError(
                f"Credit note amount {credit_note.amount} exceeds remaining balance "
                f"of invoice {invoice_id}"
            )

        new_credit_notes = self.credit_notes.copy()
        new_credit_notes[credit_note.credit_note_id] = credit_note

        # Update invoice
        new_invoice = invoice.apply_credit_note(credit_note.amount)
        new_invoices = self.invoices.copy()
        new_invoices[invoice_id] = new_invoice

        # Update customer card
        customer_card = self.customer_cards.get(invoice.customer_id)
        if customer_card:
            new_card = customer_card.apply_credit_note(credit_note.amount)
            new_cards = self.customer_cards.copy()
            new_cards[invoice.customer_id] = new_card
        else:
            new_cards = self.customer_cards

        self._register_event(
            CreditNoteIssuedEvent(
                aggregate_id=self.ar_id,
                aggregate_version=self.version + 1,
                credit_note=credit_note,
                issued_by=issued_by,
            )
        )
        self._record_audit("ADD_CREDIT_NOTE", issued_by, {"credit_note_id": str(credit_note.credit_note_id)})
        logger.info("Credit note %s added to AR subledger %s", credit_note.credit_note_id, self.ar_id)

        return self._copy_with(
            credit_notes=new_credit_notes,
            invoices=new_invoices,
            customer_cards=new_cards,
        )

    def update_invoice(
        self,
        invoice_id: UUID,
        updated_by: str,
        **updates: Any,
    ) -> ARSubledger:
        """
        Update an existing invoice.

        Args:
            invoice_id: ID of the invoice to update.
            updated_by: ID of the user performing the update.
            **updates: Fields to update (amount, description, etc.).

        Returns:
            A new ARSubledger instance with the updated invoice.

        Raises:
            InvoiceNotFoundError: If the invoice does not exist.
        """
        if invoice_id not in self.invoices:
            raise InvoiceNotFoundError(f"Invoice {invoice_id} not found")

        invoice = self.invoices[invoice_id]
        new_invoice = invoice.update(updated_by, **updates)
        new_invoices = self.invoices.copy()
        new_invoices[invoice_id] = new_invoice

        self._record_audit("UPDATE_INVOICE", updated_by, {"invoice_id": str(invoice_id), "changes": updates})
        logger.info("Invoice %s updated in AR subledger %s", invoice_id, self.ar_id)

        return self._copy_with(invoices=new_invoices)

    def delete_invoice(self, invoice_id: UUID, deleted_by: str) -> ARSubledger:
        """
        Delete an invoice (only if it has not been paid).

        Args:
            invoice_id: ID of the invoice to delete.
            deleted_by: ID of the user deleting the invoice.

        Returns:
            A new ARSubledger instance with the invoice removed.

        Raises:
            InvoiceNotFoundError: If the invoice does not exist.
            InvalidOperationError: If the invoice has been paid.
        """
        if invoice_id not in self.invoices:
            raise InvoiceNotFoundError(f"Invoice {invoice_id} not found")

        invoice = self.invoices[invoice_id]
        if invoice.paid_amount > 0:
            raise InvalidOperationError(f"Cannot delete invoice {invoice_id} because it has been paid")

        new_invoices = {k: v for k, v in self.invoices.items() if k != invoice_id}

        # Also remove from customer card
        customer_card = self.customer_cards.get(invoice.customer_id)
        if customer_card:
            new_card = customer_card.remove_invoice(invoice_id)
            new_cards = self.customer_cards.copy()
            new_cards[invoice.customer_id] = new_card
        else:
            new_cards = self.customer_cards

        self._record_audit("DELETE_INVOICE", deleted_by, {"invoice_id": str(invoice_id)})
        logger.info("Invoice %s deleted from AR subledger %s", invoice_id, self.ar_id)

        return self._copy_with(invoices=new_invoices, customer_cards=new_cards)

    # ==================== QUERY METHODS ====================

    def get_total_outstanding(self) -> Decimal:
        """Get the total outstanding balance across all customers."""
        return sum(card.outstanding_balance for card in self.customer_cards.values())

    def get_customer_outstanding(self, customer_id: UUID) -> Decimal:
        """Get the outstanding balance for a specific customer."""
        card = self.customer_cards.get(customer_id)
        return card.outstanding_balance if card else Decimal(0)

    def get_invoice(self, invoice_id: UUID) -> InvoiceEntity | None:
        """Get an invoice by ID."""
        return self.invoices.get(invoice_id)

    def get_customer_card(self, customer_id: UUID) -> CustomerCard | None:
        """Get a customer card by ID."""
        return self.customer_cards.get(customer_id)

    def get_payment(self, payment_id: UUID) -> PaymentEntity | None:
        """Get a payment by ID."""
        return self.payments.get(payment_id)

    def get_aging_summary(self, as_of: datetime | None = None) -> dict[str, Decimal]:
        """
        Get the aging summary of all outstanding invoices.

        Args:
            as_of: Date to calculate aging from (defaults to now).

        Returns:
            Dictionary with aging buckets.
        """
        if as_of is None:
            as_of = datetime.now(UTC)

        buckets = {
            "current": Decimal(0),
            "1_30": Decimal(0),
            "31_60": Decimal(0),
            "61_90": Decimal(0),
            "over_90": Decimal(0),
        }

        for card in self.customer_cards.values():
            bucket_vo = card.get_aging_bucket(as_of)
            bucket_key = {
                AgingBucket.CURRENT: "current",
                AgingBucket.DAYS_1_30: "1_30",
                AgingBucket.DAYS_31_60: "31_60",
                AgingBucket.DAYS_61_90: "61_90",
                AgingBucket.OVER_90: "over_90",
            }.get(bucket_vo.bucket)
            if bucket_key:
                buckets[bucket_key] += bucket_vo.amount

        return buckets

    def get_days_sales_outstanding(self) -> Decimal:
        """
        Calculate Days Sales Outstanding (DSO).

        Returns:
            DSO as a decimal number of days.
        """
        total_outstanding = self.get_total_outstanding()
        # Simplified: if no invoices, return 0
        if not self.invoices:
            return Decimal(0)
        # Average daily sales = total invoices / number of days in period
        # For simplicity, using total outstanding / (total invoices / 30)
        total_invoice_amount = sum(inv.amount for inv in self.invoices.values())
        if total_invoice_amount == 0:
            return Decimal(0)
        daily_sales = total_invoice_amount / Decimal(30)  # approximate
        if daily_sales == 0:
            return Decimal(0)
        return total_outstanding / daily_sales

    # ==================== VALIDATION ====================

    def validate(self) -> dict[str, Any]:
        """
        Validate all invariants and return a validation report.

        Returns:
            Dictionary with validation results.
        """
        errors = []
        for invoice in self.invoices.values():
            try:
                invoice.validate()
            except Exception as e:
                errors.append(f"Invoice {invoice.invoice_number}: {e}")

        for customer_id, card in self.customer_cards.items():
            if card.outstanding_balance < 0:
                errors.append(f"Customer {customer_id} has negative balance: {card.outstanding_balance}")
            calculated = self._calculate_customer_balance(customer_id)
            if abs(card.outstanding_balance - calculated) > Decimal("0.01"):
                errors.append(
                    f"Customer {customer_id} balance mismatch: card={card.outstanding_balance}, "
                    f"calculated={calculated}"
                )

        return {
            "is_valid": len(errors) == 0,
            "errors": errors,
            "ar_id": str(self.ar_id),
            "version": self.version,
            "total_outstanding": str(self.get_total_outstanding()),
        }

    # ==================== AUDIT & SNAPSHOT ====================

    def get_audit_trail(self, limit: int = 100) -> list[dict[str, Any]]:
        """Get the audit trail (last N entries)."""
        return self._audit_trail[-limit:]

    def get_snapshots(self) -> list[dict[str, Any]]:
        """Get all snapshots."""
        return self._snapshots.copy()

    def snapshot(self) -> dict[str, Any]:
        """
        Create a snapshot of the current state.

        Returns:
            The snapshot data.
        """
        self._take_snapshot()
        return self._snapshots[-1]

    # ==================== EVENT MANAGEMENT ====================

    def get_events(self) -> list[DomainEvent]:
        """Get all registered events."""
        return self._events.copy()

    def pull_events(self) -> list[DomainEvent]:
        """
        Get and clear all registered events.

        Returns:
            List of events that were registered.
        """
        events = self._events.copy()
        self._events.clear()
        return events

    def clear_events(self) -> None:
        """Clear all registered events."""
        self._events.clear()

    # ==================== VERSION MANAGEMENT ====================

    def get_version(self) -> int:
        """Get the current version number."""
        return self.version

    def increment_version(self) -> ARSubledger:
        """
        Increment the version number (for optimistic locking).

        Returns:
            A new ARSubledger instance with version incremented.
        """
        return self._copy_with(version=self.version + 1)

    # ==================== SERIALIZATION ====================

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the aggregate to a dictionary.

        Returns:
            Dictionary representation.
        """
        return {
            "ar_id": str(self.ar_id),
            "legal_entity_id": str(self.legal_entity_id),
            "total_invoices": len(self.invoices),
            "total_payments": len(self.payments),
            "total_customers": len(self.customer_cards),
            "total_credit_notes": len(self.credit_notes),
            "total_debit_notes": len(self.debit_notes),
            "total_outstanding": str(self.get_total_outstanding()),
            "aging_summary": {
                k: str(v) for k, v in self.get_aging_summary().items()
            },
            "dso": str(self.get_days_sales_outstanding()),
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat(),
            "version": self.version,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ARSubledger:
        """
        Reconstruct an ARSubledger from a dictionary.

        Args:
            data: Dictionary containing the subledger data.

        Returns:
            A new ARSubledger instance.
        """
        return cls(
            ar_id=UUID(data["ar_id"]),
            legal_entity_id=UUID(data["legal_entity_id"]),
            created_at=datetime.fromisoformat(data["created_at"]),
            updated_at=datetime.fromisoformat(data["updated_at"]),
            version=data.get("version", 1),
        )

    # ==================== CLONE ====================

    def clone(self, cloned_by: str = "system") -> ARSubledger:
        """
        Create a deep clone of this AR subledger.

        Args:
            cloned_by: User performing the clone operation.

        Returns:
            A new ARSubledger instance with cloned child entities.
        """
        new_id = uuid4()
        now = datetime.now(UTC)

        # Clone invoices
        cloned_invoices = {}
        for inv in self.invoices.values():
            cloned_inv = inv.clone()
            cloned_invoices[cloned_inv.invoice_id] = cloned_inv

        # Clone payments
        cloned_payments = {}
        for pmt in self.payments.values():
            cloned_pmt = pmt.clone()
            cloned_payments[cloned_pmt.payment_id] = cloned_pmt

        # Clone customer cards
        cloned_cards = {}
        for card in self.customer_cards.values():
            cloned_card = card.clone()
            cloned_cards[cloned_card.customer_id] = cloned_card

        cloned = ARSubledger(
            ar_id=new_id,
            legal_entity_id=self.legal_entity_id,
            invoices=cloned_invoices,
            payments=cloned_payments,
            customer_cards=cloned_cards,
            credit_notes=self.credit_notes.copy(),  # shallow copy, may need deep clone
            debit_notes=self.debit_notes.copy(),
            created_at=now,
            updated_at=now,
            version=1,
        )
        cloned._record_audit("CLONE", cloned_by, {"source_ar_id": str(self.ar_id)})
        logger.info("AR subledger %s cloned to %s", self.ar_id, new_id)
        return cloned

    # ==================== TOUCH / REFRESH ====================

    def touch(self, touched_by: str) -> ARSubledger:
        """
        Update the timestamp without changing any data.

        Args:
            touched_by: User performing the touch.

        Returns:
            A new ARSubledger instance with updated timestamp.
        """
        self._record_audit("TOUCH", touched_by, {})
        return self._copy_with(updated_at=datetime.now(UTC))


