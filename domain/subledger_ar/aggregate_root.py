class ARSubledgerRepository:
    """
    Repository interface for ARSubledger aggregates.

    All methods are async to support various storage backends.
    """

    async def get_by_legal_entity(self, legal_entity_id: UUID) -> ARSubledger | None:
        """Get the AR subledger for a legal entity."""
