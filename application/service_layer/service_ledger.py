async def create_ledger_service(
    ledger_repo: LedgerRepositoryPort,
    uow: UnitOfWorkPort | None = None,
    event_publisher: EventPublisherPort | None = None,
) -> LedgerService:
    return LedgerService(ledger_repo, uow, event_publisher)


